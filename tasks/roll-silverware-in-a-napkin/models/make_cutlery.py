"""Our own knife and fork models, generated in code (no third-party asset, no licence). Units: metres.
x runs along the length from the handle's end, y across the width, z up. Each rests on z = 0, tines up.
Writes knife.obj and fork.obj beside this file. Sizes are typical dinner-set values (to be matched to a named set)."""
import numpy as np
from pathlib import Path

M = 24  # points round each cross-section

def ring(x, yc, zc, w, t, p=2.6):
    """A rounded-rectangle (superellipse) cross-section of width w (y) and thickness t (z), centred at (x, yc, zc)."""
    a = np.linspace(0, 2 * np.pi, M, endpoint=False)
    c, s = np.cos(a), np.sin(a)
    return np.stack([np.full(M, x), yc + (w / 2) * np.sign(c) * np.abs(c) ** (2 / p), zc + (t / 2) * np.sign(s) * np.abs(s) ** (2 / p)], 1)

def loft(sections):
    """A closed solid through cross-sections [(x, yc, zc, w, t), ...]: side faces between rings, a fan cap at each end."""
    rings = [ring(*s) for s in sections]; v = np.concatenate(rings); n = len(rings); f = []
    for i in range(n - 1):
        for j in range(M):
            a, b, c, d = i * M + j, i * M + (j + 1) % M, (i + 1) * M + (j + 1) % M, (i + 1) * M + j
            f += [(a, b, c), (a, c, d)]
    c0, c1 = len(v), len(v) + 1
    v = np.concatenate([v, [rings[0].mean(0)], [rings[-1].mean(0)]])
    for j in range(M):
        f += [(c0, (j + 1) % M, j), (c1, (n - 1) * M + j, (n - 1) * M + (j + 1) % M)]
    return v, np.array(f)

def merge(parts):
    vs, fs, k = [], [], 0
    for v, f in parts: vs.append(v); fs.append(f + k); k += len(v)
    return np.concatenate(vs), np.concatenate(fs)

def write_obj(path, v, f, name):
    with open(path, "w") as h:
        h.write(f"# {name}: generated by make_cutlery.py, metres\no {name}\n")
        for p in v: h.write(f"v {p[0]:.6f} {p[1]:.6f} {p[2]:.6f}\n")
        for t in f: h.write(f"f {t[0]+1} {t[1]+1} {t[2]+1}\n")

cm = 0.01
def knife():
    # (distance from the handle end, sideways offset, width, thickness) in cm. Solid handle, forged bolster, blade with a
    # straight spine and an edge that curves up to a rounded tip.
    prof = [(0.0, 0.00, 0.9, 0.35), (0.25, 0.00, 1.55, 0.55), (0.8, 0.00, 1.85, 0.68), (2.0, 0.00, 1.90, 0.70), (6.0, 0.00, 1.80, 0.68),
            (10.0, 0.00, 1.62, 0.62), (11.2, 0.00, 1.55, 0.58), (11.6, 0.02, 1.62, 0.34), (12.2, 0.05, 1.86, 0.22), (15.0, 0.08, 2.00, 0.20),
            (19.5, 0.10, 2.00, 0.18), (21.5, 0.20, 1.78, 0.16), (22.8, 0.38, 1.30, 0.14), (23.6, 0.58, 0.70, 0.11), (24.0, 0.72, 0.18, 0.08)]
    half = 0.70 * cm / 2   # the handle is the thickest part; everything is centred on its mid-height so it lies flat
    return loft([(x * cm, y * cm, half, w * cm, t * cm) for x, y, w, t in prof])

def fork_z(x_cm):
    """Height of the fork's underside above the table along its length (cm): rests on the handle's end and the root of
    the tines, highest at the neck, tines curving up."""
    px = [0, 3, 7, 10.5, 12, 13.5, 15.2, 16.5, 18, 19.5]; pz = [0, 0.20, 0.62, 1.02, 1.05, 0.58, 0.0, 0.08, 0.42, 0.92]
    xs = np.linspace(0, 19.5, 400); z = np.interp(xs, px, pz); k = np.ones(31) / 31; z = np.convolve(np.pad(z, 15, mode="edge"), k, mode="valid")
    return float(np.interp(x_cm, xs, z - z.min()))

def fork():
    body = [(0.0, 1.0, 0.22), (0.25, 1.7, 0.30), (0.9, 2.05, 0.32), (2.0, 2.10, 0.32), (5.0, 1.60, 0.31), (8.0, 1.10, 0.31), (10.5, 0.78, 0.33),
            (12.2, 0.70, 0.34), (13.0, 1.20, 0.30), (13.8, 2.00, 0.26), (14.5, 2.42, 0.23), (15.3, 2.50, 0.21)]
    parts = [loft([(x * cm, 0.0, (fork_z(x) + t / 2) * cm, w * cm, t * cm) for x, w, t in body])]
    for yc in (-0.99, -0.33, 0.33, 0.99):          # four tines, 4 mm wide at the root with 2.6 mm slots
        tine = [(15.0, 0.42, 0.21), (16.5, 0.40, 0.19), (18.0, 0.36, 0.17), (19.0, 0.28, 0.14), (19.5, 0.10, 0.09)]
        parts.append(loft([(x * cm, yc * (1 - 0.06 * (x - 15.0) / 4.5) * cm, (fork_z(x) + t / 2) * cm, w * cm, t * cm) for x, w, t in tine]))
    return merge(parts)

if __name__ == "__main__":
    here = Path(__file__).resolve().parent
    for name, (v, f) in (("knife", knife()), ("fork", fork())):
        write_obj(here / f"{name}.obj", v, f, name)
        size = v.max(0) - v.min(0)
        print(f"{name}: {len(v)} vertices, {len(f)} triangles, {size[0]*100:.1f} x {size[1]*100:.2f} x {size[2]*100:.2f} cm, lowest z {v[:,2].min()*1000:.2f} mm")
